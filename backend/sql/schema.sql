-- ==========================================================
-- Schema Oracle pour le projet e-commerce (niveau etudiant)
-- Les noms de tables suivent le cahier des charges du cours.
-- ==========================================================

-- USERS + ROLES
CREATE TABLE ROLES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(30) NOT NULL UNIQUE
);

CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(120) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(30) NOT NULL,
    ROLE_ID NUMBER,
    CONSTRAINT FK_USERS_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID)
);

-- ADDRESS (liee aux utilisateurs)
CREATE TABLE ADDRESS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    STREET VARCHAR2(255) NOT NULL,
    CITY VARCHAR2(120) NOT NULL,
    POSTAL_CODE VARCHAR2(20) NOT NULL,
    COUNTRY VARCHAR2(80) NOT NULL,
    CONSTRAINT FK_ADDRESS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

-- CATEGORY + PRODUCT
CREATE TABLE CATEGORY (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(120) NOT NULL
);

CREATE TABLE PRODUCT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(180) NOT NULL,
    DESCRIPTION VARCHAR2(1000),
    PRICE NUMBER(10,2) NOT NULL,
    STOCK NUMBER NOT NULL,
    CATEGORY_ID NUMBER,
    CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(ID)
);

-- ORDERS + ORDER_ITEM
CREATE TABLE ORDERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    STATUS VARCHAR2(40) NOT NULL,
    ORDER_DATE TIMESTAMP NOT NULL,
    TOTAL_AMOUNT NUMBER(10,2)
);

CREATE TABLE ORDER_ITEM (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    PRODUCT_NAME VARCHAR2(180) NOT NULL,
    QUANTITY NUMBER NOT NULL,
    PRICE NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_ORDER_ITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID)
);

-- PAYMENT
CREATE TABLE PAYMENT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    METHOD VARCHAR2(40) NOT NULL,
    STATUS VARCHAR2(40) NOT NULL,
    AMOUNT NUMBER(10,2) NOT NULL,
    TIMESTAMP TIMESTAMP,
    CONSTRAINT FK_PAYMENT_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID)
);

